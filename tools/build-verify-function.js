/* Builds supabase/functions/verify-session/index.ts: one self-contained file with the engine,
   the session rules, the replay and the training data, so it can be deployed from the Supabase
   dashboard editor (or with `supabase functions deploy verify-session`).
   Run it again whenever the engine, the session rules or the cases change:
     node tools/build-verify-function.js */
'use strict';

const fs = require('fs');
const path = require('path');
const { load } = require('./browser-sandbox');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'supabase/functions/verify-session/index.ts');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

// Only what the engine and the session report use
const D = load().SR.data;
const data = { days: D.days, scenarios: D.scenarios, personas: D.personas, dispositions: D.dispositions, policies: D.policies };

// Each browser script runs inside a function that gives it a CommonJS "module" (no window in Deno)
const wrap = (name, file) => 'const ' + name + ' = (function () {\n  const module = { exports: {} };\n' + read(file) + '\n  return module.exports;\n})();\n';

const code = `// @ts-nocheck
// GENERATED by tools/build-verify-function.js from assets/js/engine.js, session.js, replay.js and the
// training data. Do not edit by hand: change the sources and run the script again.
//
// ShiftReady — verify-session (Supabase Edge Function)
// Replays a submitted training session with the simulator's own engine, settings and seed, and stores
// the server's result. A session is "verified" when the replay matches what the browser reported,
// "mismatch" otherwise. Only the session's owner, their coaches or their admins can ask for it.
import { createClient } from 'npm:@supabase/supabase-js@2.117.3';

const DATA = ${JSON.stringify(data)};

${wrap('ENGINE', 'assets/js/engine.js')}
${wrap('SESSION', 'assets/js/session.js')}
${wrap('REPLAY', 'assets/js/replay.js')}

const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS'
};
const json = (body, status = 200) => new Response(JSON.stringify(body), { status, headers: { ...CORS, 'Content-Type': 'application/json' } });

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: CORS });
  if (req.method !== 'POST') return json({ error: 'method_not_allowed' }, 405);
  let body;
  try { body = await req.json(); } catch (e) { return json({ error: 'invalid_body' }, 400); }
  const id = body && body.session_id;
  if (typeof id !== 'string' || !/^[0-9a-f-]{36}$/i.test(id)) return json({ error: 'invalid_session' }, 400);

  const url = Deno.env.get('SUPABASE_URL');
  const publicKey = Deno.env.get('SUPABASE_ANON_KEY') || Deno.env.get('SUPABASE_PUBLISHABLE_KEY') || req.headers.get('apikey');
  const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') || Deno.env.get('SUPABASE_SECRET_KEY');
  if (!url || !publicKey || !serviceKey) return json({ error: 'server_not_configured' }, 500);
  const auth = req.headers.get('Authorization') || '';

  // The caller must be able to see the session under the normal rules (owner, coach or admin)
  const asCaller = createClient(url, publicKey, { global: { headers: { Authorization: auth } }, auth: { persistSession: false } });
  const seen = await asCaller.from('training_sessions').select('id').eq('id', id).maybeSingle();
  if (seen.error || !seen.data) return json({ error: 'not_allowed' }, 403);

  const db = createClient(url, serviceKey, { auth: { persistSession: false } });
  const { data: s, error } = await db.from('training_sessions')
    .select('id, user_id, config, seed, status, final, log, client_report, started_at').eq('id', id).single();
  if (error || !s) return json({ error: 'not_found' }, 404);
  if (s.status === 'verified' || s.status === 'mismatch') return json({ status: s.status });
  if (s.status !== 'submitted' || !s.final) return json({ status: s.status, waiting: true });

  const prof = await db.from('profiles').select('full_name').eq('id', s.user_id).maybeSingle();
  let out;
  try {
    out = REPLAY.replay({
      data: DATA, createEngine: ENGINE.createEngine, sessionApi: SESSION,
      launch: { sid: s.id, cfg: s.config, seed: Number(s.seed), agentName: (prof.data && prof.data.full_name) || '', createdAt: s.started_at },
      days: s.log
    });
  } catch (e) {
    out = { report: null, issues: ['replay failed: ' + (e && e.message)] };
  }
  const diffs = out.report ? REPLAY.compare(out.report, s.client_report) : ['no report'];
  const ok = out.issues.length === 0 && diffs.length === 0;
  const patch = { status: ok ? 'verified' : 'mismatch', verify_notes: { issues: out.issues, diffs }, verified_at: new Date().toISOString() };
  if (out.report) Object.assign(patch, { server_report: out.report, score: out.report.totalScore, max_score: out.report.maxScore, result: out.report.status });
  const upd = await db.from('training_sessions').update(patch).eq('id', s.id).eq('status', 'submitted');
  if (upd.error) return json({ error: 'save_failed' }, 500);
  return json({ status: patch.status, issues: out.issues, diffs });
});
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, code);
console.log('verify-session written: ' + path.relative(ROOT, OUT) + ' (' + Math.round(code.length / 1024) + ' KB)');
