/* Builds supabase/functions/generate-training/index.ts: one self-contained file (scenario validator,
   reference data and one real example case) so it can be deployed from the Supabase dashboard editor.
   Run it again whenever the validator or the data format changes:
     node tools/build-generate-function.js */
'use strict';

const fs = require('fs');
const path = require('path');
const { load } = require('./browser-sandbox');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'supabase/functions/generate-training/index.ts');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

const D = load().SR.data;
const ref = { personas: D.personas, dispositions: D.dispositions, policies: D.policies, day: D.days[0] };
const example = D.scenarios.find(s => s.id === 'd1-daniel');
const validator = 'const VALIDATOR = (function () {\n  const module = { exports: {} };\n' +
  read('tools/validate-scenarios.js').replace(/^#!.*\n/, '').replace(/if \(require\.main === module\) \{[\s\S]*?\n\}\n/, '') +
  '\n  return module.exports;\n})();\n';

const code = `// @ts-nocheck
// GENERATED by tools/build-generate-function.js. Do not edit by hand: change the sources and run it again.
//
// ShiftReady — generate-training (Supabase Edge Function)
// Turns a person's prompt and documents into training cases in the simulator's own format, using
// Claude (Anthropic). Every case is checked with the simulator's scenario validator before it is
// returned; if Claude's answer has errors it is asked once to fix them. Open to visitors (no
// account) for ONE free try per address; signed-in people get a daily allowance; the whole site has a daily cap.
// Needs the secret ANTHROPIC_API_KEY (Supabase → Edge Functions → Secrets). Deploy with JWT checks OFF.
import Anthropic from 'npm:@anthropic-ai/sdk@0.132.1';
import { createClient } from 'npm:@supabase/supabase-js@2.117.3';

const REF = ${JSON.stringify(ref)};
const EXAMPLE = ${JSON.stringify(example)};
${validator}
const FREE_TRIES = 1;              // visitors without an account: one call (one day of cases), ever, per address
const LIMIT_PER_USER_DAY = 15;     // signed-in people: calls per day
const LIMIT_PER_DAY = 150;         // calls for the whole site per day
const MAX_TEXT = 60000;            // characters of prompt + documents
const MAX_PDF_BYTES = 4 * 1024 * 1024;
const CORS = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': 'authorization, apikey, content-type, x-client-info', 'Access-Control-Allow-Methods': 'POST, OPTIONS' };
const json = (body, status = 200) => new Response(JSON.stringify(body), { status, headers: { ...CORS, 'Content-Type': 'application/json' } });

const anthropic = new Anthropic({ apiKey: Deno.env.get('ANTHROPIC_API_KEY') });
const admin = createClient(Deno.env.get('SUPABASE_URL'), Deno.env.get('SUPABASE_SERVICE_ROLE_KEY'));

async function sha(text) {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(buf)].map(b => b.toString(16).padStart(2, '0')).join('');
}

// The signed-in person, if the request carries their session token (checked with Supabase Auth)
async function userFrom(req) {
  const token = (req.headers.get('authorization') || '').replace(/^Bearer\\s+/i, '');
  if (!token || token.split('.').length !== 3) return null;
  const { data, error } = await admin.auth.getUser(token);
  return error || !data.user ? null : data.user;
}

async function allowed(ip, user) {
  const key = await sha('shiftready:' + ip);
  const dayAgo = new Date(Date.now() - 86400e3).toISOString();
  const all = await admin.from('ai_usage').select('id', { count: 'exact', head: true }).gte('created_at', dayAgo);
  if ((all.count || 0) >= LIMIT_PER_DAY) return { ok: false, why: 'daily_limit' };
  if (user) {
    const mine = await admin.from('ai_usage').select('id', { count: 'exact', head: true }).eq('user_id', user.id).gte('created_at', dayAgo);
    if ((mine.count || 0) >= LIMIT_PER_USER_DAY) return { ok: false, why: 'rate_limited' };
  } else {
    const tries = await admin.from('ai_usage').select('id', { count: 'exact', head: true }).eq('ip_hash', key).is('user_id', null);
    if ((tries.count || 0) >= FREE_TRIES) return { ok: false, why: 'trial_used' };
  }
  await admin.from('ai_usage').insert({ ip_hash: key, user_id: user ? user.id : null });
  return { ok: true };
}

const SYSTEM = \`You write training cases for ShiftReady, a customer-service chat simulator. Each case is one JSON object in the
simulator's exact data format. Follow the format of the EXAMPLE case precisely: same field names and value types.
Rules the simulator enforces:
- id: unique kebab-case string. day: the number you are given. arrive: seconds after the shift starts (0, then 25-60 apart).
- persona: one of \${Object.keys(REF.personas).join(', ')}. channel: one of web, app, whatsapp, messenger. priority: Low, Medium, High or Urgent.
- verified: true, false or "na". disp: array of disposition ids from DISPOSITIONS (the right wrap-up codes when resolved).
- policies: array of policy keys from POLICIES that the case trains (may be empty if the company's own rules apply).
- nodes: an object of conversation steps. start names the first node. A node has c (customer messages, array of strings) and
  either o (2-4 reply options) or end ("resolved" or "unresolved"). Each option has q (0 poor, 1 needs work, 2 good, 3 excellent),
  t (the agent's reply text), fb (coach feedback explaining why), and go (next node id) or end. Exactly one best option per node
  should have q 3. Wrong options must sound plausible. Every go must point to an existing node; every path must reach an end.
- Use {agent} for the agent's first name and {first} for the customer's first name inside texts.
- Base facts, policies and tone on the company's prompt and documents when given. Write in the language the person uses.
Answer with ONLY a JSON array of case objects, no prose and no code fences.\`;

function parseCases(text) {
  const t = text.trim().replace(/^\\\`\\\`\\\`(?:json)?\\s*/i, '').replace(/\\\`\\\`\\\`\\s*$/, '');
  const start = t.indexOf('['), end = t.lastIndexOf(']');
  if (start === -1 || end === -1) throw new Error('no JSON array in the answer');
  const arr = JSON.parse(t.slice(start, end + 1));
  if (!Array.isArray(arr) || !arr.length) throw new Error('empty answer');
  return arr;
}

function check(cases, dayN) {
  const day = Object.assign({}, REF.day, { n: dayN });
  const data = { days: [day], scenarios: cases, personas: REF.personas, dispositions: REF.dispositions, policies: REF.policies };
  const r = VALIDATOR.validate(data);
  return r.errors.map(e => (e.scenario ? e.scenario + ': ' : '') + (e.message || e.code));
}

async function ask(messages) {
  const stream = anthropic.beta.messages.stream({
    model: 'claude-opus-5-5',
    max_tokens: 32000,
    output_config: { effort: 'medium' },
    betas: ['server-side-fallback-2026-07-01'],
    fallbacks: 'default',
    system: SYSTEM,
    messages
  });
  const msg = await stream.finalMessage();
  if (msg.stop_reason === 'refusal') throw Object.assign(new Error('refused'), { code: 'refused' });
  if (msg.stop_reason === 'max_tokens') throw Object.assign(new Error('too long'), { code: 'too_long' });
  return msg.content.filter(b => b.type === 'text').map(b => b.text).join('');
}

Deno.serve(async req => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: CORS });
  if (req.method !== 'POST') return json({ error: 'method_not_allowed' }, 405);
  let body;
  try { body = await req.json(); } catch (e) { return json({ error: 'invalid_request' }, 400); }
  const prompt = String(body.prompt || '').slice(0, MAX_TEXT);
  const docs = (Array.isArray(body.docs) ? body.docs : []).slice(0, 10).map(d => ({ name: String(d.name || '').slice(0, 120), text: String(d.text || '') }));
  const pdfs = (Array.isArray(body.pdfs) ? body.pdfs : []).slice(0, 3).filter(p => typeof p.data === 'string' && p.data.length * 0.75 <= MAX_PDF_BYTES);
  const dayN = Math.max(100, Math.min(199, parseInt(body.day, 10) || 100));
  const count = Math.max(1, Math.min(3, parseInt(body.count, 10) || 2));
  const plan = String(body.plan || '').slice(0, 2000);
  if (!prompt.trim() && !docs.length && !pdfs.length) return json({ error: 'empty' }, 400);
  if (prompt.length + docs.reduce((s, d) => s + d.text.length, 0) > MAX_TEXT) return json({ error: 'too_much_text' }, 413);

  const ip = (req.headers.get('x-forwarded-for') || '').split(',')[0].trim() || 'unknown';
  const user = await userFrom(req);
  const gate = await allowed(ip, user);
  if (!gate.ok) return json({ error: gate.why }, 429);

  const content = [];
  pdfs.forEach(p => content.push({ type: 'document', source: { type: 'base64', media_type: 'application/pdf', data: p.data.replace(/\\s+/g, '') }, title: String(p.name || 'documento.pdf').slice(0, 120) }));
  let text = 'EXAMPLE case (format reference only):\\n' + JSON.stringify(EXAMPLE) +
    '\\n\\nPOLICIES (keys and titles): ' + JSON.stringify(Object.fromEntries(Object.entries(REF.policies).map(([k, v]) => [k, v.title]))) +
    '\\nDISPOSITIONS: ' + JSON.stringify(REF.dispositions.map(d => d.id)) +
    '\\n\\nThe person\\'s request and prompt:\\n' + (prompt || '(none)') +
    docs.map(d => '\\n\\n--- Document: ' + d.name + ' ---\\n' + d.text).join('') +
    '\\n\\nThis day of the training: ' + (plan || 'day ' + (dayN - 99)) +
    '\\nWrite exactly ' + count + ' new cases with day = ' + dayN + '.';
  content.push({ type: 'text', text });

  try {
    const messages = [{ role: 'user', content }];
    let answer = await ask(messages), cases, errors;
    try { cases = parseCases(answer); errors = check(cases, dayN); } catch (e) { cases = null; errors = ['The answer was not a valid JSON array: ' + e.message]; }
    if (errors.length) {
      messages.push({ role: 'assistant', content: answer }, { role: 'user', content: 'The simulator\\'s validator found these errors. Return the full corrected JSON array only:\\n- ' + errors.slice(0, 30).join('\\n- ') });
      answer = await ask(messages);
      cases = parseCases(answer);
      errors = check(cases, dayN);
      if (errors.length) return json({ error: 'invalid_cases', details: errors.slice(0, 10) }, 422);
    }
    cases.forEach(c => { c.day = dayN; });
    return json({ cases });
  } catch (e) {
    if (e.code === 'refused') return json({ error: 'refused' }, 422);
    if (e.code === 'too_long') return json({ error: 'too_long' }, 422);
    if (e instanceof Anthropic.AuthenticationError) return json({ error: 'ai_not_configured' }, 503);
    if (e instanceof Anthropic.RateLimitError) return json({ error: 'ai_busy' }, 503);
    if (e instanceof Anthropic.APIError) return json({ error: 'ai_error', status: e.status }, 502);
    return json({ error: 'server_error', message: String(e.message || e).slice(0, 200) }, 500);
  }
});
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, code);
console.log('Wrote', path.relative(ROOT, OUT), Math.round(code.length / 1024) + ' KB');
