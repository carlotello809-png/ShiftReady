  function removeCustomDays() {
    for (let i = D.days.length - 1; i >= 0; i--) if (isCustomDay(D.days[i].n)) D.days.splice(i, 1);
    for (let i = D.scenarios.length - 1; i >= 0; i--) if (isCustomDay(D.scenarios[i].day)) D.scenarios.splice(i, 1);
  }
  // Plays a training generated by the chat: { days: [{ n, title, level, focus }], cases: [...] }.
  // Its days are added only for this session and removed when going back to the lobby.
  SR.playTraining = function (t) {
    removeCustomDays();
    const ns = [];
    t.days.forEach(d => {
      if (!isCustomDay(d.n) || !t.cases.some(c => c.day === d.n)) return;
      const level = d.level || 'Medium';
      D.days.push(Object.assign({}, D.days[0], { n: d.n, title: String(d.title || 'Custom day').slice(0, 60), level,
        replyIn: { Easy: 60, Medium: 45, Hard: 38, Expert: 30 }[level] || 45,
        summary: d.summary || 'Generated training day.', focus: (d.focus || []).slice(0, 4), tip: '' }));
      ns.push(d.n);
    });
    t.cases.forEach(c => { if (ns.indexOf(c.day) !== -1) D.scenarios.push(c); });
    if (!ns.length) return false;
    return startSession(ns, { difficulty: t.difficulty || 'medium' });
  };

